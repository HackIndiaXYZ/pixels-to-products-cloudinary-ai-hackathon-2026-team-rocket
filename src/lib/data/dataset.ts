const HOUR = 3_600_000;

export function buildSampleAssets(now: number): MediaAsset[] {
  return SAMPLES.map(({ hoursAgo, fixedAt, ...spec }) => ({
    ...spec,
    cloudName: DEMO_CLOUD,
    source: 'sample' as const,
    captureBasis: fixedAt ? ('fixed' as const) : ('sample-relative' as const),
    capturedAt: fixedAt ? new Date(fixedAt).toISOString() : new Date(now - (hoursAgo ?? 0) * HOUR).toISOString(),
  }));
}

/** Deterministic snapshot for server rendering (dates are not shown from it). */
export const SAMPLE_IDS = SAMPLES.map((s) => s.id);
